"""Задача 02. Сумма

Ввод: два целых числа в одной строке, например «5 7».
Вывод — каждое в своей строке: сумма, разность, произведение,
целочисленное деление (//) и остаток (%).
"""

import sys

def main():
    n1, n2 = map (int, input().split())
    print(f"{n1+n2}")
    print(f"{n1-n2}")
    print(f"{n1 * n2}")
    print(f"{n1//n2}")
    print(f"{n1 % n2}")

if __name__ == "__main__":
    main()
